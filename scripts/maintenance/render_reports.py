"""Render reviewed report records and their index; never acquire data or train."""

import argparse
import json
from pathlib import Path

from codexa.reporting import cell, render_report


def render_tree(root: Path, *, check: bool = False) -> None:
    outputs: dict[Path, str] = {}
    records = []
    for source in sorted(root.glob("*/evidence/*-report.json")):
        record = json.loads(source.read_text())
        destination = source.parent.parent / (record["report_id"] + ".md")
        if destination in outputs:
            raise ValueError("Duplicate report destination")
        outputs[destination] = render_report(record)
        records.append((destination.relative_to(root), record))
    if not records:
        raise ValueError("No report records found")
    order = {"training": 0, "evaluation": 1, "datasets": 2, "benchmarks": 3, "language": 4}
    records.sort(key=lambda item: (order.get(item[0].parts[0], 5), item[0].as_posix()))
    lines = [
        "<!-- Generated by scripts/maintenance/render_reports.py. -->",
        "# Research reports",
        "",
        (
            "Read the findings first, then inspect each report's measurement scope and evidence. "
            "Statuses apply to the named assessment and date, not the project as a whole."
        ),
        "",
        (
            "[Project overview](../README.md) · [Documentation](../docs/index.md) · "
            "[Current training workflow](../docs/training.md)"
        ),
        "",
    ]
    for historical, title, description in (
        (
            False,
            "Research results",
            (
                "Completed training, language evaluation, mathematics admission and recorded "
                "engineering measurements."
            ),
        ),
        (
            True,
            "Historical decisions",
            (
                "Earlier source reviews, storage captures and the superseded 1B readiness "
                "proposal. Their original outcomes remain recorded."
            ),
        ),
    ):
        group = [
            (path, record)
            for path, record in records
            if record.get("historical", False) == historical
        ]
        if not group:
            continue
        lines += [
            "## " + title,
            "",
            description,
            "",
            "| Report | Recorded status / date | Finding |",
            "| --- | --- | --- |",
        ]
        for path, record in group:
            lines.append(
                f"| [{cell(record['title'])}]({path.as_posix()}) | "
                f"{cell(record['status'])} · {cell(record['date'])} | "
                f"{cell(record.get('takeaway', record['summary'][0]))} |"
            )
        lines.append("")
    lines += [
        "## How to read a status",
        "",
        (
            "- **PASS** means the named check or capture passed. A completed run or benchmark "
            "does not establish language competence."
        ),
        "- **FAIL** preserves a failed evaluation or admission decision.",
        "- **BLOCKED** identifies unresolved requirements at the report date.",
        "- **IN PROGRESS** identifies unfinished work or an unpromoted tool summary.",
        "",
        (
            "Source quality, internal-use rights, training authorization and actual execution "
            "are separate decisions. None independently approves public weight distribution."
        ),
        "",
        "## Evidence and archives",
        "",
        (
            "Each report exposes its artifact locations and SHA-256 checksums in an expandable "
            "evidence section. Raw corpora, checkpoints and protected assessments stay outside Git."
        ),
        "",
        "- [Original benchmark JSON](benchmarks/evidence/): retained measurements and hardware scope.",
        "- [Research archive](archive/index.json): original documents captured on 10 November 2026.",
        "- [Earlier engineering archive](../docs/archive/index.json): 17 checksummed original documents.",
        "",
        "## Maintain these reports",
        "",
        (
            "Edit reviewed `evidence/*-report.json` records and regenerate with "
            "`python -m scripts.maintenance.render_reports`. "
            "[Contributing](../CONTRIBUTING.md#documentation-and-reports) describes the record format "
            "and checks. Regeneration runs no experiments and does not change raw evidence."
        ),
        "",
    ]
    outputs[root / "README.md"] = "\n".join(lines)
    for path, text in outputs.items():
        if check:
            if not path.exists() or path.read_text() != text:
                raise ValueError("Stale generated report: " + str(path))
        else:
            path.write_text(text)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--records", type=Path, default=Path("reports"))
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    render_tree(args.records, check=args.check)


if __name__ == "__main__":
    main()
