"""Render reviewed report records and their index; never acquire data or train."""

import argparse
import json
from pathlib import Path

from codexa.reporting import render_report


def render_tree(root: Path, *, check: bool = False) -> None:
    outputs: dict[Path, str] = {}
    records = []
    for source in sorted(root.glob("*/evidence/*-report.json")):
        record = json.loads(source.read_text())
        destination = source.parent.parent / (record["report_id"] + ".md")
        if destination in outputs:
            raise ValueError("Duplicate report destination")
        outputs[destination] = render_report(record)
        records.append((destination.relative_to(root), record))
    if not records:
        raise ValueError("No report records found")
    lines = [
        "<!-- Generated by scripts/maintenance/render_reports.py. -->",
        "# Research reports",
        "",
        "Current summaries are separated from immutable machine evidence and historical snapshots. Dates and statuses apply only to the named run and scope.",
        "",
        "| Workstream / report | Status | Date | Run |",
        "| --- | --- | --- | --- |",
    ]
    for path, record in records:
        lines.append(
            f"| [{record['title']}]({path.as_posix()}) | {record['status']} | {record['date']} | {record['run_id']} |"
        )
    lines += [
        "",
        "## Evidence and history",
        "",
        "- Reviewed report inputs: each workstream's `evidence/*-report.json`; change these records and regenerate, rather than editing generated Markdown.",
        "- [Original benchmark JSON](benchmarks/evidence/) retains its original bytes, hardware scope and limitations.",
        "- [Research snapshot archive](archive/index.json): original guides and reports captured on 2026-11-10, with member checksums. Historical failures remain historical failures.",
        "- [Earlier engineering archive](../docs/archive/index.json): 17 original checksummed documents.",
        "- [Documentation index](../docs/index.md): setup, architecture, training, datasets and release policy.",
        "",
        "Raw corpus text, protected assessments, private ratings, checkpoints and large generated artifacts remain outside Git. A quality PASS never grants permission to launch training.",
        "",
    ]
    outputs[root / "README.md"] = "\n".join(lines)
    for path, text in outputs.items():
        if check:
            if not path.exists() or path.read_text() != text:
                raise ValueError("Stale generated report: " + str(path))
        else:
            path.write_text(text)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--records", type=Path, default=Path("reports"))
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    render_tree(args.records, check=args.check)


if __name__ == "__main__":
    main()
